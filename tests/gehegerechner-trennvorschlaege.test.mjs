import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { getRechnerDaten } from '../assets/js/rechner/rechnerBerechnung.js';
import { automatischeTrennVorschlaege } from '../assets/js/rechner/trennEmpfehlungen.js';
import { profilAusZoopedia } from '../assets/js/rechner/zonenLogik.js';
const basis = new URL('../assets/daten/lebewesen/tiere/',import.meta.url).pathname;
function art(name, anzahl=2) {
  const walk=(dir)=>{for(const d of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,d.name); if(d.isDirectory()){const found=walk(p);if(found)return found;}else if(d.name===name+'.json')return p;}return null;};
  const p=walk(basis); if(!p)throw new Error('Tier fehlt: '+name);
  const originalDaten=JSON.parse(fs.readFileSync(p,'utf8'));
  const tier={id:name,datenId:name,wissenschaftlicherName:name,originalDaten};
  return {tier,name,anzahl,maennchen:1,weibchen:anzahl-1,jungtiere:0,rechner:getRechnerDaten(tier)};
}
const binturong=art('Arctictis binturong');
const sunbear=art('Helarctos malayanus');
const flamingo=art('Phoenicopterus roseus');
const buffalo=art('Syncerus caffer caffer');
const kata=art('Lemur catta',3);
const fish=art('Hydrocynus vittatus',5);
assert.equal(profilAusZoopedia(kata).faehigkeiten.klettern,true);
assert.equal(profilAusZoopedia(sunbear).faehigkeiten.klettern,true);
assert.equal(profilAusZoopedia(flamingo).faehigkeiten.fliegen,true);
let paar=automatischeTrennVorschlaege([binturong,sunbear]).paare[0];
assert.ok(paar.gemeinsam.includes('klettern'),'Beide Arten klettern: Klettern als gemeinsame Fähigkeit erkannt');
assert.ok(!paar.varianten.some((v)=>v.typ==='klettern'), 'Klettern beider Arten darf KEINE funktionierende Trennung vortäuschen');
assert.match(paar.varianten.find((v)=>v.typ==='engstelle').richtung,/Arctictis binturong/);
assert.equal(paar.varianten.find((v)=>v.typ==='engstelle').sicherheit,'unbestaetigt');
paar=automatischeTrennVorschlaege([flamingo,buffalo]).paare[0];
assert.equal(paar.relation.status,'neutral','Zoopedia-Beziehung nicht mit unbekannt verwechseln');
assert.ok(paar.varianten.some((v)=>v.typ==='fliegen'),'Flugroute wird automatisch vorgeschlagen');
assert.equal(paar.varianten.find((v)=>v.typ==='fliegen').sicherheit,'unbestaetigt', 'Unbekannte Flugfähigkeit beim Büffel nicht als Negation deuten');
assert.ok(!paar.bevorzugt,'Keine sichere Behauptung ohne explizite Negation');
paar=automatischeTrennVorschlaege([fish,buffalo]).paare[0];
assert.ok(paar.varianten.some((v)=>v.typ==='ufer-tiefwasser'),'Gemeinsames Ufer/Tiefwasser statt Aquarienpflicht');
const testA={...kata,tier:{...kata.tier,id:'flieger'},name:'Flieger',rechner:{...kata.rechner,fortbewegung:{...kata.rechner.fortbewegung,fliegen:true}}};
const testB={...buffalo,tier:{...buffalo.tier,id:'nichtflieger'},name:'Nichtflieger',rechner:{...buffalo.rechner,fortbewegung:{...buffalo.rechner.fortbewegung,fliegen:false}}};
paar=automatischeTrennVorschlaege([testA,testB]).paare[0];
assert.ok(paar.varianten.some((v)=>v.typ==='fliegen'&&v.sicherheit==='datenbasiert'),'Ja/Nein ergibt belegten Bewegungsunterschied');
assert.equal(automatischeTrennVorschlaege([kata]).paare.length,0);
const visiting=automatischeTrennVorschlaege([flamingo,buffalo]).besucher;
assert.ok(visiting.some((v)=>v.tier===flamingo.name&&v.fernzuhalten===buffalo.name));
console.log('Automatische Trennvorschläge: alle Tests bestanden.');
