#!/usr/bin/env bash

set -euo pipefail


# ============================================================
# PROJEKTPFADE
# ============================================================

SCRIPT_DIR="$(
    cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &&
    pwd
)"

PROJECT_ROOT="$(
    cd -- "$SCRIPT_DIR/.." &&
    pwd
)"


cd "$PROJECT_ROOT"


# ============================================================
# COMMIT-NACHRICHT
# ============================================================

COMMIT_MESSAGE="$*"


if [[ -z "$COMMIT_MESSAGE" ]]
then

    echo
    read -r -p "Commit-Nachricht: " COMMIT_MESSAGE

fi


if [[ -z "$COMMIT_MESSAGE" ]]
then

    echo
    echo "❌ Keine Commit-Nachricht angegeben."

    exit 1

fi


# ============================================================
# GIT PRÜFEN
# ============================================================

if ! git rev-parse --is-inside-work-tree > /dev/null 2>&1
then

    echo
    echo "❌ Dieser Ordner ist kein Git-Repository."

    exit 1

fi


BRANCH="$(
    git branch --show-current
)"


echo
echo "============================================================"
echo "PlanetZoo2 Commit"
echo "============================================================"
echo
echo "Branch:"
echo "$BRANCH"
echo
echo "Commit:"
echo "$COMMIT_MESSAGE"


# ============================================================
# AUTOMATISCHE MD ERSTELLEN
# ============================================================

echo
echo "============================================================"
echo "1. Automatische MD erstellen"
echo "============================================================"
echo

"$SCRIPT_DIR/ordnerstruktur.sh"


# ============================================================
# .GITIGNORE AUS JSON + STANDARD ERSTELLEN
# ============================================================

echo
echo "============================================================"
echo "2. .gitignore gemäss JSON + Standard erstellen"
echo "============================================================"
echo

python3 "$SCRIPT_DIR/gitignore-aus-json.py"


# ============================================================
# PROJEKT FORMATIEREN
# ============================================================

echo
echo "============================================================"
echo "3. Gesamtes Projekt mit Prettier formatieren"
echo "============================================================"
echo

"$SCRIPT_DIR/format.sh"


# ============================================================
# SHARE-ZIP
# ============================================================

echo
echo "============================================================"
echo "4. Share-ZIP erstellen"
echo "============================================================"
echo

"$SCRIPT_DIR/share-zip.sh"


# ============================================================
# GIT STATUS
# ============================================================

echo
echo "============================================================"
echo "5. Git-Status"
echo "============================================================"
echo


git status --short


# ============================================================
# GIT ADD
# ============================================================

echo
echo "============================================================"
echo "6. Git add"
echo "============================================================"
echo


git add -A


# ============================================================
# PRÜFEN OB ÄNDERUNGEN VORHANDEN SIND
# ============================================================

if git diff --cached --quiet
then

    echo
    echo "ℹ️ Keine Änderungen für einen Commit vorhanden."

    exit 0

fi


# ============================================================
# COMMIT
# ============================================================

echo
echo "============================================================"
echo "7. Git commit"
echo "============================================================"
echo


git commit \
    -m "$COMMIT_MESSAGE"


# ============================================================
# PUSH
# ============================================================

echo
echo "============================================================"
echo "8. Git push"
echo "============================================================"
echo


git push


# ============================================================
# FERTIG
# ============================================================

echo
echo "============================================================"
echo "✅ Alles abgeschlossen"
echo "============================================================"
echo
echo "Ordnerstruktur:"
echo "dokumentation/ordnerstruktur.md"
echo
echo "Share-ZIP:"
echo "share/"
echo
echo "Git:"
echo "Commit + Push erfolgreich"
echo